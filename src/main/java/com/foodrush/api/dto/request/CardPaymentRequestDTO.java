package com.foodrush.api.dto.request;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

@Schema(description = "Credit card payment payload with tokenized card data")
public record CardPaymentRequestDTO(
    @NotBlank(message = "Card token is required")
    @Schema(description = "Tokenized card string generated by Mercado Pago JS SDK", example = "9b2d63e00d66a8c212d2657e80ac6070")
    String token,

    @NotNull(message = "Installments is required")
    @Min(value = 1, message = "Minimum installments is 1")
    @Schema(description = "Selected number of installments", example = "1")
    Integer installments,

    @NotBlank(message = "Payment method ID is required")
    @Schema(description = "Payment method brand ID (e.g. visa, master, elo, amex)", example = "master")
    String paymentMethodId,

    @Schema(description = "Bank issuer ID", example = "25")
    String issuerId
) {}
